//! High-bandwidth GEMV for single-token / small-batch decode.
//!
//! cuBLASLt's batch-invariance contract forces one algorithm per weight
//! `(m, k)` shape, chosen at a tuning column count (32), so at `n = 1` it
//! streams weights well below the memory ceiling. This kernel instead fixes
//! the *reduction order* rather than the algorithm: each output column is a
//! dot product whose partial sums live in one lane and are combined by a
//! five-step warp tree, so the result depends only on `k`, never on the live
//! batch size. That lets every decode column count use the same fast path.
//!
//! Layout: A is row-major `[m, k]` weights, B is column-major `[k, n]`
//! (activations, one contiguous vector per token) and C is column-major
//! `[m, n]`. One warp owns one output row; four warps share a block. Each
//! lane reads eight consecutive k elements (one 16-byte vector load) per
//! 256-element group, so weight and activation traffic is fully coalesced.
//! `n` is tiled 16 columns at a time to bound register pressure; the tile
//! width only changes how often A is re-read, never the arithmetic.
//!
//! Status: NOT wired into the engine. `test_gemv` shows why. It matches the
//! cuBLASLt path at n=1 (0.029 ms vs 0.033 ms for 2048x2048; 1.616 ms vs the
//! in-engine 1.548 ms for the 128000x2048 lm_head), then falls off a cliff:
//! each column tile re-reads the whole weight matrix, so 2048x2048 drops from
//! 289 GB/s at n=1 to 88 GB/s at n=16 and 42 GB/s at n=17. Serving only the
//! small-n range would make a token depend on batch composition, which the
//! batch-invariance guarantee forbids, so the engine keeps cuBLASLt and the
//! fused four-row lm_head GEMV.

/// `gemv_fp16(a, x, c, m, k, n)` with f32 accumulation and f16 output.
